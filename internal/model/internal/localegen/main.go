// Command localegen writes ../../localedata.go: the language tags offered by the language autocompleter (with their
// English names from CLDR) and the IANA time zones offered by the time zone autocompleter. Run from internal/model:
//
//	go run ./internal/localegen /usr/share/zoneinfo/tzdata.zi
//
// The zones are the canonical ones in the given tzdata.zi that Go's embedded time zone database also knows.
package main

import (
	"archive/zip"
	"bufio"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"

	"golang.org/x/text/language"
	"golang.org/x/text/language/display"
)

// tags: languages, and regional variants where they differ in practice (spelling, formats, currency).
var tags = strings.Fields(`
af am ar ar-AE ar-EG ar-SA az be bg bn bs ca cs cy da de de-AT de-CH el en en-AU en-CA en-GB en-IE en-IN
en-NZ en-SG en-US en-ZA es es-419 es-AR es-CL es-CO es-ES es-MX es-US et eu fa fi fil fr fr-BE fr-CA fr-CH
fr-FR ga gl gu he hi hr hu hy id is it it-CH ja ka kk km kn ko ky lo lt lv mk ml mn mr ms mt my nb ne nl
nl-BE nn pa pl pt pt-BR pt-PT ro ru si sk sl sq sr sr-Latn sv sw ta te th tr uk ur uz vi zh-Hans zh-Hant
zh-HK zh-TW zu`)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: localegen <tzdata.zi>")
	}
	// "Language (Region)" or "Language (Script)": searching "English" finds every English.
	langs, regions, scripts := display.English.Languages(), display.English.Regions(), display.English.Scripts()
	scriptNames := map[string]string{"Simplified Han": "Simplified", "Traditional Han": "Traditional"}
	type loc struct{ tag, name string }
	var locs []loc
	for _, t := range tags {
		tag := language.MustParse(t)
		base, _ := tag.Base()
		name := langs.Name(base)
		if name == "" {
			log.Fatalf("no name for %s", t)
		}
		if r, conf := tag.Region(); conf == language.Exact {
			n := regions.Name(r)
			if n == "Hong Kong SAR China" {
				n = "Hong Kong"
			}
			name += " (" + n + ")"
		} else if sc, conf := tag.Script(); conf == language.Exact {
			n := scripts.Name(sc)
			if v, ok := scriptNames[n]; ok {
				n = v
			}
			name += " (" + n + ")"
		}
		locs = append(locs, loc{tag.String(), name})
	}
	sort.Slice(locs, func(i, j int) bool { return locs[i].name < locs[j].name })

	known := map[string]bool{}
	zr, err := zip.OpenReader(filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		log.Fatal(err)
	}
	for _, f := range zr.File {
		known[f.Name] = true
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var zones []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fs := strings.Fields(sc.Text())
		if len(fs) >= 2 && fs[0] == "Z" && known[fs[1]] && !strings.HasPrefix(fs[1], "Etc/") {
			zones = append(zones, fs[1])
		}
	}
	zones = append(zones, "UTC")
	sort.Strings(zones)

	var b strings.Builder
	b.WriteString("// Code generated by internal/localegen; DO NOT EDIT.\n\npackage model\n\n")
	b.WriteString("// Locales are the language tags offered when choosing a user's language, by English name.\n")
	b.WriteString("var Locales = []LocaleOption{\n")
	for _, l := range locs {
		fmt.Fprintf(&b, "\t{%q, %q},\n", l.tag, l.name)
	}
	b.WriteString("}\n\n// TimeZones are the canonical IANA time zones offered when choosing a user's time zone.\n")
	b.WriteString("var TimeZones = []string{\n")
	for _, z := range zones {
		fmt.Fprintf(&b, "\t%q,\n", z)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("localedata.go", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d locales, %d zones\n", len(locs), len(zones))
}
